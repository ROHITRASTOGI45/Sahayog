import { Router } from "express";
import { multerStorage } from "../../shared/middleware/upload.middleware.js";
import { verifyCooperativeAdminJWT } from "../../shared/middleware/auth.middleware.js";
import { requireCooperativeAdmin } from "../../shared/middleware/role.middleware.js";
import { rateLimit } from "../../shared/middleware/rate-limit.middleware.js";
import { registerOwner, registerAdmin, loginAdmin, logoutAdmin, joinRequests, acceptRequest, rejectRequest, dashboard, workers, worker, workerStatus, workerExperienceCategory, searchWorker, serviceRequests, reports, settings, profile } from "./cooperative-admin.controller.js";
const router = Router();
router.post("/register-owner", rateLimit({ max: 5 }), multerStorage.single("profilePhoto"), registerOwner);
router.post("/login", rateLimit({ max: 8 }), loginAdmin);
router.use(verifyCooperativeAdminJWT, requireCooperativeAdmin);
router.post("/register", registerAdmin);
router.post("/logout", logoutAdmin);
router.get("/join-requests", joinRequests);
router.patch("/join-requests/:requestId/accept", acceptRequest);
router.patch("/join-requests/:requestId/reject", rejectRequest);
router.get("/dashboard", dashboard);
router.get("/workers", workers);
router.get("/search-worker", searchWorker);
router.get("/service-requests", serviceRequests);
router.get("/reports", reports);
router.get("/settings", settings);
router.patch("/settings", settings);
router.get("/profile", profile);
router.patch("/profile", profile);
router.get("/workers/:workerId", worker);
router.patch("/workers/:workerId/status", workerStatus);
router.patch("/workers/:workerId/experience-category", workerExperienceCategory);
export default router;
